-- ==============================================================================
-- 8. TABLA DE PEDIDOS Y VENTAS (orders)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    order_number TEXT UNIQUE NOT NULL,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_phone TEXT,
    customer_doc TEXT,
    shipping_address TEXT NOT NULL,
    shipping_neighborhood TEXT,
    shipping_city TEXT NOT NULL DEFAULT 'Cartagena de Indias',
    shipping_department TEXT NOT NULL DEFAULT 'Bolívar',
    shipping_country TEXT NOT NULL DEFAULT 'Colombia',
    shipping_zone_id BIGINT REFERENCES public.shipping_zones(id) ON DELETE SET NULL,
    payment_method TEXT DEFAULT 'nequi', -- 'card', 'pse', 'nequi', 'daviplata', 'cash'
