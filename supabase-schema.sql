-- Función para actualizar rating y conteo de reseñas en products
CREATE OR REPLACE FUNCTION update_product_reviews_aggregate()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE public.products
    SET 
        rating = COALESCE((SELECT ROUND(AVG(rating)::numeric, 2) FROM public.reviews WHERE product_id = COALESCE(NEW.product_id, OLD.product_id) AND status = 'Aprobada'), 5.0),
        reviews_count = COALESCE((SELECT COUNT(*) FROM public.reviews WHERE product_id = COALESCE(NEW.product_id, OLD.product_id) AND status = 'Aprobada'), 0)
    WHERE id = COALESCE(NEW.product_id, OLD.product_id);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_update_reviews_aggregate ON public.reviews;
CREATE TRIGGER trg_update_reviews_aggregate
AFTER INSERT OR UPDATE OR DELETE ON public.reviews
FOR EACH ROW EXECUTE FUNCTION update_product_reviews_aggregate();

