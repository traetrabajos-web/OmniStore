-- OMNISTORE CARTAGENA - ESQUEMA PROFESIONAL DE BASE DE DATOS POSTGRESQL
-- ==============================================================================
-- Plataforma E-Commerce OmniStore + Panel Administrativo + Tienda Pública
-- Exclusivo para Cartagena de Indias, Bolívar, Colombia (Moneda: COP $)
-- Compatible con Supabase PostgreSQL (https://supabase.com) y PostgreSQL 14+
-- ==============================================================================

-- EXTENSIONES NECESARIAS
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ==============================================================================
-- 1. TABLA DE USUARIOS Y PERFILES (users)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'customer' CHECK (role IN ('admin', 'vendor', 'support', 'accountant', 'customer', 'user')),
    avatar TEXT DEFAULT './assets/images/avatar-placeholder.svg',
    phone TEXT,
    document_type TEXT DEFAULT 'CC', -- 'CC', 'NIT', 'CE', 'PASAPORTE'
    document_number TEXT,
    address TEXT,
    neighborhood TEXT, -- Barrio en Cartagena (Bocagrande, Manga, Crespo, etc.)
    city TEXT NOT NULL DEFAULT 'Cartagena de Indias',
    department TEXT NOT NULL DEFAULT 'Bolívar',
    country TEXT NOT NULL DEFAULT 'Colombia',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'pending', 'suspended')),
    last_login TIMESTAMPTZ
);

-- ==============================================================================
-- 2. LIBRETA DE DIRECCIONES DE CLIENTES (user_addresses)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.user_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    recipient_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    neighborhood TEXT NOT NULL,
    address_line TEXT NOT NULL,
    details TEXT, -- Apto, casa, conjunto, etc.
    city TEXT NOT NULL DEFAULT 'Cartagena de Indias',
    department TEXT NOT NULL DEFAULT 'Bolívar',
    zone_code TEXT DEFAULT 'Z1', -- Z1 (Bocagrande/Centro), Z2 (Manga/Crespo), Z3 (El Bosque), Z4 (Turbaco/Mamonal)
    is_default BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 3. TABLA DE CATEGORÍAS (categories)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    name TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    icon TEXT DEFAULT 'bi-grid',
    description TEXT,
    item_count INT DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive'))
);

-- ==============================================================================
-- 4. TABLA DE PRODUCTOS (products)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    name TEXT NOT NULL,
    sku TEXT UNIQUE NOT NULL,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    category_slug TEXT DEFAULT 'electronics',
    category_label TEXT DEFAULT 'Tecnología',
    brand TEXT,
    price NUMERIC(12,2) NOT NULL DEFAULT 0.00, -- Precio en Pesos Colombianos (COP)
    original_price NUMERIC(12,2),
    cost_price NUMERIC(12,2),
    discount_percent INT DEFAULT 0,
    stock INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_left INT DEFAULT 0,
    stock_total INT DEFAULT 0,
    min_stock_alert INT DEFAULT 5,
    status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'draft', 'out_of_stock', 'archived')),
    rating NUMERIC(3,2) DEFAULT 5.0,
    reviews_count INT DEFAULT 0,
    sales_count INT DEFAULT 0,
    is_flash_deal BOOLEAN DEFAULT FALSE,
    is_best_seller BOOLEAN DEFAULT FALSE,
    has_free_shipping BOOLEAN DEFAULT FALSE,
    badge_text TEXT,
    image TEXT DEFAULT './assets/images/product-placeholder.svg',
    images JSONB DEFAULT '[]'::jsonb,
    colors JSONB DEFAULT '["Predeterminado"]'::jsonb,
    sizes JSONB DEFAULT '[]'::jsonb,
    description TEXT,
    tags JSONB DEFAULT '["cartagena", "tecnologia", "omnistore"]'::jsonb
);

-- ==============================================================================
-- 5. CARRITO DE COMPRAS PERSISTENTE (cart_items)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    quantity INT NOT NULL DEFAULT 1 CHECK (quantity > 0),
    selected_color TEXT DEFAULT 'Predeterminado',
    selected_size TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uq_user_product_variant UNIQUE(user_id, product_id, selected_color, selected_size)
);

-- ==============================================================================
-- 6. TABLA DE CUPONES Y DESCUENTOS (coupons)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    code TEXT UNIQUE NOT NULL,
    discount_type TEXT NOT NULL DEFAULT 'percentage' CHECK (discount_type IN ('percentage', 'fixed', 'free_shipping')),
    discount_value NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    min_order_amount NUMERIC(12,2) DEFAULT 0.00,
    max_uses INT DEFAULT 1000,
    used_count INT DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    expires_at TIMESTAMPTZ,
    description TEXT
